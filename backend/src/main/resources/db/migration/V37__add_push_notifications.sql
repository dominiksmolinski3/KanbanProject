CREATE TABLE push_endpoints (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY,
    user_id    integer      NOT NULL,
    device_id  bigint       NOT NULL,
    kind       varchar(16)  NOT NULL,
    endpoint   text         NOT NULL,
    p256dh     varchar(255),
    auth       varchar(255),
    created_at timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

ALTER TABLE push_endpoints
    ADD CONSTRAINT uq_push_endpoints_device_kind UNIQUE (device_id, kind);
ALTER TABLE push_endpoints
    ADD CONSTRAINT fk_push_endpoints_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE push_endpoints
    ADD CONSTRAINT fk_push_endpoints_device FOREIGN KEY (device_id) REFERENCES crypto_devices (id) ON DELETE CASCADE;
CREATE INDEX idx_push_endpoints_user ON push_endpoints (user_id);
CREATE INDEX idx_push_endpoints_device ON push_endpoints (device_id);

CREATE TABLE push_outbox (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY,
    endpoint_id     bigint       NOT NULL,
    conversation_id bigint       NOT NULL,
    seq             bigint       NOT NULL,
    attempts        integer      NOT NULL DEFAULT 0,
    next_attempt_at timestamp(6) WITH TIME ZONE NOT NULL,
    created_at      timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

