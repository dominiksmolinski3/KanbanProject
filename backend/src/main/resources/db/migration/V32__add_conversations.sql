CREATE TABLE conversations (
    id                 bigint      GENERATED BY DEFAULT AS IDENTITY,
    kind               varchar(16) NOT NULL,
    direct_key         varchar(32),
    group_id           bytea       NOT NULL,
    epoch              bigint      NOT NULL,
    next_seq           bigint      NOT NULL,
    needs_commit       boolean     NOT NULL,
    history_visibility varchar(16) NOT NULL,
    who_can_add        varchar(16) NOT NULL,
    created_by         integer,
    created_at         timestamp(6) WITH TIME ZONE NOT NULL,
    last_activity_at   timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

ALTER TABLE conversations
    ADD CONSTRAINT uq_conversations_direct_key UNIQUE (direct_key);
ALTER TABLE conversations
    ADD CONSTRAINT uq_conversations_group_id UNIQUE (group_id);
ALTER TABLE conversations
    ADD CONSTRAINT fk_conversations_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL;
CREATE INDEX idx_conversations_created_by ON conversations (created_by);

CREATE TABLE conversation_members (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY,
    conversation_id bigint      NOT NULL,
    user_id         integer     NOT NULL,
    role            varchar(16) NOT NULL,
    state           varchar(16) NOT NULL,
    joined_seq      bigint      NOT NULL,
    read_seq        bigint      NOT NULL,
    muted           boolean     NOT NULL,
    pinned          boolean     NOT NULL,
    archived        boolean     NOT NULL,
    joined_at       timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

ALTER TABLE conversation_members
