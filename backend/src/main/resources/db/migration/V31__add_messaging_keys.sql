--
-- Messaging keys, phase 1 of the end-to-end encrypted messenger.
--
-- The server holds public keys and opaque bytes only. identity_keys.wrapped_private is the
-- identity's private half sealed under the optional recovery key; identity_pins.wrapped_private is
-- the same half sealed under a key only an exchange with the server's PIN secret can produce.
--
-- A device outlives sign-outs and records the sign-in it is attached to: a refresh rotates the
-- token row, so refresh_tokens gains chain_id, set once at sign-in and carried by every rotation.
-- Existing rows each start a chain of their own.
--

ALTER TABLE refresh_tokens ADD COLUMN chain_id uuid;
UPDATE refresh_tokens SET chain_id = gen_random_uuid();
ALTER TABLE refresh_tokens ALTER COLUMN chain_id SET NOT NULL;
CREATE INDEX idx_refresh_tokens_chain ON refresh_tokens (chain_id);

CREATE TABLE identity_keys (
    user_id         integer NOT NULL,
    public_key      bytea   NOT NULL,
    wrapped_private bytea,
    created_at      timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id)
);

ALTER TABLE identity_keys
    ADD CONSTRAINT fk_identity_keys_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;

CREATE TABLE identity_pins (
    user_id         integer NOT NULL,
    wrapped_private bytea   NOT NULL,
    verifier        bytea   NOT NULL,
    failed_attempts integer NOT NULL,
    updated_at      timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id)
);

ALTER TABLE identity_pins
    ADD CONSTRAINT fk_identity_pins_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;

CREATE TABLE crypto_devices (
    id                 bigint  GENERATED BY DEFAULT AS IDENTITY,
    user_id            integer NOT NULL,
    session_chain      uuid    NOT NULL,
    signature_key      bytea   NOT NULL,
    credential         bytea   NOT NULL,
    identity_signature bytea   NOT NULL,
    label              varchar(255),
    created_at         timestamp(6) WITH TIME ZONE NOT NULL,
    last_seen_at       timestamp(6) WITH TIME ZONE NOT NULL,
    revoked_at         timestamp(6) WITH TIME ZONE,
    PRIMARY KEY (id)
);

ALTER TABLE crypto_devices
    ADD CONSTRAINT fk_crypto_devices_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
CREATE INDEX idx_crypto_devices_user ON crypto_devices (user_id);
CREATE INDEX idx_crypto_devices_chain ON crypto_devices (session_chain);

CREATE TABLE key_packages (
    id          bigint  GENERATED BY DEFAULT AS IDENTITY,
    device_id   bigint  NOT NULL,
    ref         bytea   NOT NULL,
    data        bytea   NOT NULL,
    last_resort boolean NOT NULL,
    created_at  timestamp(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

ALTER TABLE key_packages
    ADD CONSTRAINT uq_key_packages_ref UNIQUE (ref);
ALTER TABLE key_packages
    ADD CONSTRAINT fk_key_packages_device FOREIGN KEY (device_id) REFERENCES crypto_devices (id) ON DELETE CASCADE;
CREATE INDEX idx_key_packages_device ON key_packages (device_id);
